def geometry(selected, pdf, shared_layer=None, stem='05_count_geometry'):
    clouds = pd.concat([read(LEGACY/m/'geometry/projection_cloud.csv') for m in MODES], ignore_index=True)
    fig, aa = canvas(2, 2, (11, 8.7))
    fig.subplots_adjust(right=.90, bottom=.11, hspace=.42, wspace=.30)
    points = []
    for row, answer in enumerate([False, True]):
        for col, mode in enumerate(MODES):
            chosen = selected.loc[selected['mode'].eq(mode) & selected.endpoint.str.contains('answer_query').eq(answer)].iloc[0]
            layer = int(chosen.selected_layer) if shared_layer is None else shared_layer
            f = clouds.loc[clouds.endpoint.eq(chosen.endpoint) & clouds.layer.eq(layer) & clouds.split.eq('confirmation')].copy()
            assert len(f) == (100 if answer else 550)
            assert f.prompt_sha256.nunique() == 100
            points.append(f)
            ax = aa[row, col]
            im = ax.scatter(f.pc1, f.pc2, c=f.occurrence, cmap=COUNT, vmin=1, vmax=10, s=12 if not answer else 20, alpha=.62, linewidths=0, rasterized=True)
            centroids = f.groupby('occurrence')[['pc1', 'pc2']].mean()
            ax.plot(centroids.pc1, centroids.pc2, color=GRAY, lw=.8, alpha=.6)
            ax.scatter(centroids.pc1, centroids.pc2, c=centroids.index, cmap=COUNT, vmin=1, vmax=10, s=50, edgecolors=INK, linewidths=.55, zorder=4)
            kind = 'Final count' if answer else 'Running index'
            panel(ax, f'({chr(97+2*row+col)}) {NAMES[mode]}: {kind}, L{layer}')
            ax.set_xlabel(f'PC1 ({100*f.pc1_variance_ratio.iloc[0]:.1f}% discovery variance)')
            ax.set_ylabel(f'PC2 ({100*f.pc2_variance_ratio.iloc[0]:.1f}%)')
