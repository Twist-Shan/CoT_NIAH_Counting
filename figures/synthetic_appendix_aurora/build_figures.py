def layout_audit(fig, stem):
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    from matplotlib.text import Text
    texts = [t for t in fig.findobj(Text) if t.get_visible() and t.get_text() and t.get_window_extent(renderer).width>0]
    bounds = fig.bbox
    clipped = []
    for t in texts:
        b = t.get_window_extent(renderer)
        # Ignore hidden/out-of-range tick labels generated by locators.
        if t.axes is not None and t not in t.axes.texts and t not in [t.axes.xaxis.label,t.axes.yaxis.label,t.axes._left_title]:
            continue
        if b.x0 < -1 or b.y0 < -1 or b.x1 > bounds.x1+1 or b.y1 > bounds.y1+1:
            clipped.append(t.get_text())
    LAYOUT_CHECKS.append({'figure':stem, 'width_inches':float(fig.get_figwidth()),
                          'min_font_points':min(t.get_fontsize() for t in texts),
                          'min_font_at_5_5_inches':min(t.get_fontsize() for t in texts)*5.5/fig.get_figwidth(),
                          'outside_page_text':clipped})
    if clipped:
        print('LAYOUT CHECK', stem, json.dumps(clipped,ensure_ascii=True), flush=True)


def read(path):
    path = Path(path)
    SOURCES[str(path.relative_to(WORK))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return pd.read_csv(path)


def read_json(path):
    path = Path(path)
    SOURCES[str(path.relative_to(WORK))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return json.loads(path.read_text(encoding='utf-8'))


def export(frame, name):
    frame.to_csv(TABLES / (name + '.csv'), index=False)
    return frame


def panel(ax, title, ylabel=None, percent=False):
    ax.set_title(title, loc='left', pad=10)
    if ylabel:
        ax.set_ylabel(ylabel)
    ax.grid(axis='y', color='#E8E8ED', linewidth=.65)
    ax.set_axisbelow(True)
    for side in ['top', 'right']:
        ax.spines[side].set_visible(False)
    if percent:
        ax.set_ylim(-3, 103)
        ax.set_yticks([0, 20, 40, 60, 80, 100])


def time_axis(ax, symlog=False):
    ax.axvline(1500, color=GRAY, linestyle=':', linewidth=1)
    ax.set_xlabel('Training step')
    if symlog:
        ax.set_xscale('symlog', linthresh=200, linscale=.65)
        ticks = [0, 200, 1000, 10000]
    else:
        ticks = [0, 2500, 5000, 7500, 10000]
    ax.set_xticks(ticks)
    ax.xaxis.set_major_formatter(FuncFormatter(lambda x, _: f'{x/1000:g}k' if x >= 1000 else f'{x:g}'))
    ax.set_xlim(0, 10000)


def canvas(rows=1, cols=2, size=None):
    fig, axes = plt.subplots(rows, cols, figsize=size or (5.2*cols, 3.8*rows+.7), squeeze=False)
    fig.subplots_adjust(left=.075, right=.985, top=.90, bottom=.18 if rows == 1 else .11, wspace=.30, hspace=.40)
    return fig, axes


def save(fig, stem, title, caption, note, pdf):
    paper_layout(fig, stem)
    layout_audit(fig, stem)
    caption = caption.replace('Panels (a,b)', 'Panels A and B').replace('Panel (c)', 'Panel C')
    note = note.replace('Panels (a,b)', 'Panels A and B').replace('Panel (c)', 'Panel C')
    for suffix in ['pdf', 'svg', 'png']:
        fig.savefig(OUT / f'{stem}.{suffix}', dpi=300, facecolor='white', bbox_inches='tight', pad_inches=.055)
    pdf.savefig(fig, dpi=300, facecolor='white', bbox_inches='tight', pad_inches=.055)
    shutil.copy2(OUT / f'{stem}.pdf', PAPER / f'{stem}.pdf')
    FIGURES.append(dict(stem=stem, title=title, caption=caption, note=note))
    plt.close(fig)
    print('Saved', stem, flush=True)


def validate_panel(frame, groups, expected, key='key'):
    for group, f in frame.groupby(groups, dropna=False):
        assert len(f) == len(expected) and set(f[key]) == expected, (groups, group, len(f))
    CHECKS.append({'groups': groups, 'rows': len(frame), 'inputs_per_condition': len(expected), 'aligned': True})


def training_behavior(ablation, pdf):
    loss = read(DATA/'tables/eval_loss_curves.csv')
    loss = loss.loc[loss.position_encoding.eq('rope') & loss.suite.eq('task')]
    export(loss, '01_evaluation_loss')
    clean = ablation.loc[ablation.arm.eq('clean')]
    behavior = export(clean.groupby(['mode', 'count']).agg(accuracy=('ar_accuracy', 'mean'), inputs=('key', 'nunique')).reset_index(), '01_behavior_by_count')
    assert set(behavior.inputs) == {10}
    fig, aa = canvas(cols=3, size=(13.5, 4.5))
    for i, mode in enumerate(MODES):
        ax = aa[0, i]
        for source, label, style in [('train', 'Training-region evaluation', '-'), ('heldout', 'Validation-region evaluation', '--')]:
            f = loss.loc[loss['mode'].eq(mode) & loss.curve_source.eq(source)].sort_values('step')
            assert len(f) and not f.duplicated('step').any()
            ax.plot(f.step, f.token_weighted_cross_entropy, color=COLORS[mode], ls=style, label=label)
        panel(ax, f'({chr(97+i)}) {NAMES[mode]}: evaluation loss', 'Token cross-entropy')
        ax.legend(fontsize=8.5, loc='lower right')
        time_axis(ax)
    ax = aa[0, 2]
    for mode in MODES:
        f = behavior.loc[behavior['mode'].eq(mode)]
        ax.plot(f['count'], 100*f.accuracy, 'o-', color=COLORS[mode], label=NAMES[mode])
    panel(ax, '(c) Final-checkpoint counting', 'Free-generation accuracy (%)', True)
    ax.set(xlabel='True count', xticks=range(1, 11))
    ax.legend(loc='lower right')
    save(fig, '01_training_and_behavior', 'Training and counting behavior',
         'Full-sequence token-weighted evaluation cross-entropy on training and validation regions, using the archived evaluation curves. This is a fixed evaluation metric rather than the weighted training objective. The dotted line marks the objective change at step 1,500. The final-checkpoint accuracy panel uses ten confirmation inputs per count and mode; missing numeric answers are incorrect.',
         'Loss: archived evaluation suites. Accuracy: 100 confirmation inputs per mode (10 per count). One training run per mode.', pdf)


def retrieval_ablation(ablation, pdf):
    summary = export(ablation.groupby(['mode', 'arm', 'top_k', 'repeat']).agg(answer=('ar_accuracy', 'mean'), answered=('ar_answered', 'mean'), trace=('trace_exact', 'mean')).reset_index(), '02_retrieval_ablation')
    fig, aa = canvas(2, 2, (11.5, 8))
    specs = [('nonthinking', 'answer', 'Non-thinking: answer accuracy'), ('nonthinking', 'answered', 'Non-thinking: numeric-answer rate'), ('thinking', 'answer', 'Thinking: answer accuracy'), ('thinking', 'trace', 'Thinking: complete-trace accuracy')]
    for i, (mode, metric, title) in enumerate(specs):
        ax = aa.flat[i]
        f = summary.loc[summary['mode'].eq(mode)]
        baseline = float(f.loc[f.arm.eq('clean'), metric].iloc[0])
        selected = f.loc[f.arm.eq('selected')].groupby('top_k')[metric].mean()
        controls = f.loc[f.arm.eq('random')].groupby('top_k')[metric].mean()
        for k in [1, 2, 4]:
            vals = f.loc[f.arm.eq('random') & f.top_k.eq(k), metric].to_numpy()
            ax.scatter(np.full(len(vals), k), 100*vals, s=28, marker='x', color=GRAY, alpha=.85, zorder=4)
        ax.plot([0]+selected.index.tolist(), 100*np.r_[baseline, selected.values], 'o-', color=COLORS[mode], label='Selected retrieval heads')
        ax.plot([0]+controls.index.tolist(), 100*np.r_[baseline, controls.values], 's--', color=GRAY, label='Layer-matched controls: mean')
        panel(ax, f'({chr(97+i)}) {title}', 'Rate (%)', True)
        ax.set(xlabel='Number of ablated heads', xticks=[0, 1, 2, 4])
        ax.legend(fontsize=9, loc='upper right' if i == 0 else 'lower left')
    save(fig, '02_retrieval_ablation', 'Retrieval-head ablation',
         'Heads are selected on discovery inputs. Non-thinking ablation acts at the answer query; Thinking ablation acts at trace-separator queries, followed by free generation. Selected and control conditions reuse the same 100 confirmation inputs. Crosses show individual control sets (three for K=1/2; one for K=4). The non-thinking numeric-answer panel exposes the severe output failure under some controls.',
         'Same 100 inputs per condition. Gray crosses: individual matched controls. K=0: clean baseline.', pdf)


def roles_transport(pdf):
    factorial = read(LEGACY/'thinking/factorial_trials.csv')
    role = export(factorial.groupby('arm')[['ar_accuracy', 'trace_exact', 'trace_marker_count_accuracy']].mean().reset_index(), '03_head_functions')
    arms = ['clean', 'targeted_top2', 'successor_top1', 'successor_control_0', 'successor_control_1', 'successor_control_2', 'broad_top2', 'targeted_plus_successor', 'targeted_plus_broad']
    labels = ['Clean', 'Targeted Top-2', 'Successor L2H3', 'Successor control 1', 'Successor control 2', 'Successor control 3', 'Answer broad Top-2', 'Targeted + successor', 'Targeted + answer broad']
    role = role.set_index('arm').loc[arms]
    fig, aa = canvas(cols=3, size=(15, 5.8))
    fig.subplots_adjust(left=.15, wspace=.55, bottom=.16)
    for j, metric in enumerate(['ar_accuracy', 'trace_exact']):
        ax = aa[0, j]
        for i, arm in enumerate(arms):
            color = GRAY if 'control' in arm else VIOLET if 'successor' in arm else COLORS['thinking']
            value = float(role.loc[arm, metric])*100
            ax.plot([0, value], [i, i], color=color, alpha=.28, lw=2)
            ax.scatter(value, i, color=color, s=40, zorder=3)
            ax.text(value+1.8, i, f'{value:.0f}', va='center', fontsize=9)
        panel(ax, '(a) Final answer' if j == 0 else '(b) Complete trace')
        ax.set(yticks=range(len(arms)), yticklabels=labels if j == 0 else [], xlim=(0, 109), xlabel='Accuracy (%)')
        ax.invert_yaxis()
        ax.grid(axis='x', color='#E8E8ED')
    transport = read(LEGACY/'thinking/transport_trials.csv')
    ts = export(transport.groupby(['condition', 'top_k', 'repeat'])[['clean_margin', 'corrupt_margin', 'margin', 'restoration']].mean().reset_index(), '03_value_transport')
    ax = aa[0, 2]
    for cond, name, color, style in [('value_selected', 'Selected heads', COLORS['thinking'], '-'), ('value_control', 'Matched controls', GRAY, '--')]:
        f = ts.loc[ts.condition.eq(cond)].groupby('top_k').margin.mean()
        ax.plot(f.index, f.values, 'o'+style, color=color, label=name)
    for cond, label, color in [('clean', 'Clean', VIOLET), ('damaged', 'Damaged', ORANGE)]:
        val = float(ts.loc[ts.condition.eq(cond), 'margin'].iloc[0])
        ax.axhline(val, color=color, ls=':', label=label)
    ax.axhline(0, color=INK, lw=.6)
    panel(ax, '(c) Source-value restoration', 'Correct-minus-replacement logit margin')
    ax.set(xlabel='Number of patched heads', xticks=[1, 2, 4])
    ax.legend(fontsize=9, loc='center left')
    save(fig, '03_head_functions_and_transport', 'Head functions and content transport',
         'The factorial ablations compare targeted retrieval, successor L2H3, answer-side broad heads, and joint interventions on the same 100 free-generation inputs. Three matched successor controls are displayed separately (Succ. denotes successor). Broad refers to answer-side broad heads. The value-patching panel changes one source character and restores clean values at that source; it measures a local correct-versus-replacement logit margin, not whole-trace recovery. Control curves average three sets for K=1/2 and one set for K=4.',
         'Thinking, 100 inputs per condition. Panels (a,b): free generation. Panel (c): gold-prefix local prediction.', pdf)


